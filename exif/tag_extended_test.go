func TestTagRegistry_ReferenceTablesCovered(t *testing.T) {
	t.Parallel()
	tables := []struct {
		name string
		tags []refTag
	}{
		{"libtiff/tiffFields", libtiffTIFFTags},
		{"libtiff/exifFields", libtiffEXIFTags},
		{"libtiff/gpsFields", libtiffGPSTags},
		{"metadata-extractor/ExifDirectoryBase", metadataExtractorTags},
		{"DNG-1.7.1.0", dngSpecTags},
	}
	for _, tbl := range tables {
		for _, r := range tbl.tags {
			if TagName(r.id) == "" {
				t.Errorf("%s: tag 0x%04X (%s) has no registry entry", tbl.name, uint16(r.id), r.name)
			}
		}
	}
}

// TestTagRegistry_ExtendedTagsConsistent proves extendedTags neither repeats an
// ID nor shadows a hand-written entry, and that every entry is well formed.
func TestTagRegistry_ExtendedTagsConsistent(t *testing.T) {
	t.Parallel()
	const baseTags = 152 // entries of the hand-written literal in tag.go
	if got, want := len(tagRegistry), baseTags+len(extendedTags); got != want {
		t.Fatalf("len(tagRegistry) = %d, want %d (extended IDs must be unique and not collide with tag.go)", got, want)
	}
	for _, e := range extendedTags {
		if e.info.Name == "" {
			t.Errorf("extended tag 0x%04X has an empty name", uint16(e.id))
		}
		if e.info.Type == 0 || e.info.Type > TypeUTF8 {
			t.Errorf("extended tag 0x%04X (%s) has invalid type %d", uint16(e.id), e.info.Name, e.info.Type)
		}
		if got := tagRegistry[e.id]; got != e.info {
			t.Errorf("tag 0x%04X: registry holds %+v, want %+v", uint16(e.id), got, e.info)
		}
	}
}

// TestTagName_DNGNamesMatchSpec checks the registered name of every DNG tag
// against the DNG Specification 1.7.1.0 tag reference.
func TestTagName_DNGNamesMatchSpec(t *testing.T) {
	t.Parallel()
	for _, r := range dngSpecTags {
		if got := TagName(r.id); got != r.name {
			t.Errorf("TagName(0x%04X) = %q, want %q (DNG 1.7.1.0)", uint16(r.id), got, r.name)
		}
	}
}

